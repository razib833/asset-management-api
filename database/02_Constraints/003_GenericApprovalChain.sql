        STEP_NAME             NVARCHAR(150) NOT NULL,
        APPROVER_SOURCE       VARCHAR(40) NOT NULL,
        APPROVAL_UNIT_ID      BIGINT NULL,
        EMPLOYEE_ID           VARCHAR(30) NULL,
        APPROVER_ROLE_CODE    VARCHAR(50) NULL,
        APPROVAL_MODE         VARCHAR(15) NOT NULL CONSTRAINT DF_WORKFLOW_RULE_STEP_MODE DEFAULT ('ANY_ONE'),
        REQUIRED_APPROVAL_COUNT INT NOT NULL CONSTRAINT DF_WORKFLOW_RULE_STEP_COUNT DEFAULT (1),
        IS_OPTIONAL           BIT NOT NULL CONSTRAINT DF_WORKFLOW_RULE_STEP_OPTIONAL DEFAULT (0),
        COMPLETION_DESTINATION VARCHAR(50) NULL,
        IS_ACTIVE             BIT NOT NULL CONSTRAINT DF_WORKFLOW_RULE_STEP_ACTIVE DEFAULT (1),
        CREATED_BY            VARCHAR(30) NULL,
        CREATED_ON            DATETIME2(0) NOT NULL CONSTRAINT DF_WORKFLOW_RULE_STEP_CREATED DEFAULT SYSUTCDATETIME(),
        UPDATED_BY            VARCHAR(30) NULL,
        UPDATED_ON            DATETIME2(0) NULL,
        ROW_VERSION           ROWVERSION,
        CONSTRAINT CK_WORKFLOW_RULE_STEP_ORDER CHECK (STEP_ORDER > 0),
        CONSTRAINT CK_WORKFLOW_RULE_STEP_SOURCE CHECK (APPROVER_SOURCE IN ('EMPLOYEE','APPROVAL_UNIT','ROLE_POOL','REQUESTING_UNIT_MANAGER','CONCERN_DIVISION_OFFICIAL','PROCUREMENT_AUTHORITY')),
        CONSTRAINT CK_WORKFLOW_RULE_STEP_MODE CHECK (APPROVAL_MODE IN ('ANY_ONE','ALL','COUNT')),
        CONSTRAINT CK_WORKFLOW_RULE_STEP_COUNT CHECK (REQUIRED_APPROVAL_COUNT > 0),
        CONSTRAINT CK_WORKFLOW_RULE_STEP_MAPPING CHECK
        (
            (APPROVER_SOURCE = 'EMPLOYEE' AND EMPLOYEE_ID IS NOT NULL) OR
            (APPROVER_SOURCE = 'APPROVAL_UNIT' AND APPROVAL_UNIT_ID IS NOT NULL) OR
            (APPROVER_SOURCE = 'ROLE_POOL' AND APPROVER_ROLE_CODE IS NOT NULL) OR
            APPROVER_SOURCE IN ('REQUESTING_UNIT_MANAGER','CONCERN_DIVISION_OFFICIAL','PROCUREMENT_AUTHORITY')
        ),
        CONSTRAINT FK_WORKFLOW_RULE_STEP_RULE FOREIGN KEY (WORKFLOW_RULE_ID) REFERENCES dbo.WORKFLOW_RULE(WORKFLOW_RULE_ID),
        CONSTRAINT FK_WORKFLOW_RULE_STEP_UNIT FOREIGN KEY (APPROVAL_UNIT_ID) REFERENCES dbo.APPROVAL_UNIT(APPROVAL_UNIT_ID),
        CONSTRAINT FK_WORKFLOW_RULE_STEP_EMP FOREIGN KEY (EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID),
        CONSTRAINT FK_WORKFLOW_RULE_STEP_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID),
        CONSTRAINT FK_WORKFLOW_RULE_STEP_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID)
    );
