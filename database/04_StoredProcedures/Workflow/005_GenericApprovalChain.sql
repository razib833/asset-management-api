CREATE OR ALTER PROCEDURE dbo.usp_WorkflowRuleStep_GetByRule @WorkflowRuleId BIGINT
AS
BEGIN
    SET NOCOUNT ON;
    -- Keep this projection in the same order as WorkflowRuleStepDto.  The API
    -- uses CommandBehavior.SequentialAccess, so SELECT s.* followed by joined
    -- columns would force the reader to seek backwards from UNIT_CODE to
    -- EMPLOYEE_ID and fail at runtime.
    SELECT s.WORKFLOW_RULE_STEP_ID,
           s.WORKFLOW_RULE_ID,
           s.STEP_ORDER,
           s.STEP_CODE,
           s.STEP_NAME,
           s.APPROVER_SOURCE,
           s.APPROVAL_UNIT_ID,
           u.UNIT_CODE,
           u.UNIT_NAME,
           s.EMPLOYEE_ID,
           c.DISPLAY_NAME AS EMPLOYEE_NAME,
           s.APPROVER_ROLE_CODE,
           s.APPROVAL_MODE,
           s.REQUIRED_APPROVAL_COUNT,
           s.IS_OPTIONAL,
           s.COMPLETION_DESTINATION,
           s.IS_ACTIVE
    FROM dbo.WORKFLOW_RULE_STEP s
    LEFT JOIN dbo.APPROVAL_UNIT u ON u.APPROVAL_UNIT_ID=s.APPROVAL_UNIT_ID
    LEFT JOIN dbo.APP_USER_CACHE c ON c.EMPLOYEE_ID=s.EMPLOYEE_ID
    WHERE s.WORKFLOW_RULE_ID=@WorkflowRuleId AND s.IS_ACTIVE=1 ORDER BY s.STEP_ORDER;
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_WorkflowApprovalChain_Initialize
    @WorkflowInstanceId BIGINT,
    @ActorEmployeeId VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    DECLARE @RuleId BIGINT,@ReqId BIGINT,@FirstStepId BIGINT,@FirstCode VARCHAR(50),@FirstEmployee VARCHAR(30),@FirstOrg BIGINT;
    SELECT @RuleId=WORKFLOW_RULE_ID,@ReqId=REQUISITION_ID FROM dbo.WORKFLOW_INSTANCE WHERE WORKFLOW_INSTANCE_ID=@WorkflowInstanceId;
    IF @RuleId IS NULL THROW 50008, 'Workflow instance or matched rule was not found.', 1;
    IF NOT EXISTS(SELECT 1 FROM dbo.WORKFLOW_RULE_STEP WHERE WORKFLOW_RULE_ID=@RuleId AND IS_ACTIVE=1) THROW 50009, 'No generic approval steps are configured for this workflow rule.', 1;
    IF EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE_STEP WHERE WORKFLOW_INSTANCE_ID=@WorkflowInstanceId) THROW 50010, 'The generic approval chain has already been initialized.', 1;

    BEGIN TRAN;
    INSERT dbo.WORKFLOW_INSTANCE_STEP(WORKFLOW_INSTANCE_ID,SOURCE_RULE_STEP_ID,STEP_ORDER,STEP_CODE,STEP_NAME,APPROVER_SOURCE,APPROVAL_UNIT_ID,CONFIGURED_EMPLOYEE_ID,APPROVER_ROLE_CODE,APPROVAL_MODE,REQUIRED_APPROVAL_COUNT,IS_OPTIONAL,COMPLETION_DESTINATION)
    SELECT @WorkflowInstanceId,WORKFLOW_RULE_STEP_ID,STEP_ORDER,STEP_CODE,STEP_NAME,APPROVER_SOURCE,APPROVAL_UNIT_ID,EMPLOYEE_ID,APPROVER_ROLE_CODE,APPROVAL_MODE,REQUIRED_APPROVAL_COUNT,IS_OPTIONAL,COMPLETION_DESTINATION
    FROM dbo.WORKFLOW_RULE_STEP WHERE WORKFLOW_RULE_ID=@RuleId AND IS_ACTIVE=1;

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID,AUTHORITY_LEVEL)
    SELECT s.WORKFLOW_INSTANCE_STEP_ID,a.EMPLOYEE_ID,a.AUTHORITY_LEVEL
    FROM dbo.WORKFLOW_INSTANCE_STEP s JOIN dbo.APPROVAL_UNIT_APPROVER a ON a.APPROVAL_UNIT_ID=s.APPROVAL_UNIT_ID
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.APPROVER_SOURCE='APPROVAL_UNIT' AND a.IS_ACTIVE=1
      AND (s.APPROVER_ROLE_CODE IS NULL OR a.APPROVER_ROLE_CODE=s.APPROVER_ROLE_CODE)
      AND (a.EFFECTIVE_FROM IS NULL OR a.EFFECTIVE_FROM<=CONVERT(date,SYSUTCDATETIME())) AND (a.EFFECTIVE_TO IS NULL OR a.EFFECTIVE_TO>=CONVERT(date,SYSUTCDATETIME()));

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID)
    SELECT WORKFLOW_INSTANCE_STEP_ID,CONFIGURED_EMPLOYEE_ID FROM dbo.WORKFLOW_INSTANCE_STEP
    WHERE WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND APPROVER_SOURCE='EMPLOYEE';

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID)
    SELECT s.WORKFLOW_INSTANCE_STEP_ID,o.EMPLOYEE_ID FROM dbo.WORKFLOW_INSTANCE_STEP s
    JOIN dbo.WORKFLOW_RULE r ON r.WORKFLOW_RULE_ID=@RuleId
    JOIN dbo.CONCERN_DIVISION_OFFICIAL o ON o.CONCERN_DIVISION_ID=r.CONCERN_DIVISION_ID AND o.IS_ACTIVE=1
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.APPROVER_SOURCE='CONCERN_DIVISION_OFFICIAL'
      AND o.EFFECTIVE_FROM<=CONVERT(date,SYSUTCDATETIME()) AND (o.EFFECTIVE_TO IS NULL OR o.EFFECTIVE_TO>=CONVERT(date,SYSUTCDATETIME()));

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID)
    SELECT s.WORKFLOW_INSTANCE_STEP_ID,p.EMPLOYEE_ID FROM dbo.WORKFLOW_INSTANCE_STEP s CROSS JOIN dbo.PROC_AUTHORITY p
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.APPROVER_SOURCE='PROCUREMENT_AUTHORITY' AND p.IS_ACTIVE=1
      AND p.EFFECTIVE_FROM<=CONVERT(date,SYSUTCDATETIME()) AND (p.EFFECTIVE_TO IS NULL OR p.EFFECTIVE_TO>=CONVERT(date,SYSUTCDATETIME()));

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID)
    SELECT DISTINCT s.WORKFLOW_INSTANCE_STEP_ID,u.EMPLOYEE_ID FROM dbo.WORKFLOW_INSTANCE_STEP s
    JOIN dbo.ROLE_MASTER rm ON rm.ROLE_CODE=s.APPROVER_ROLE_CODE AND rm.IS_ACTIVE=1
    JOIN dbo.DEV_USER_ROLE ur ON ur.ROLE_ID=rm.ROLE_ID AND ur.IS_ACTIVE=1
    JOIN dbo.DEV_USER du ON du.DEV_USER_ID=ur.DEV_USER_ID AND du.IS_ACTIVE=1
    JOIN dbo.APP_USER_CACHE u ON u.EMPLOYEE_ID=du.EMPLOYEE_ID AND u.IS_ACTIVE=1
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.APPROVER_SOURCE='ROLE_POOL';

    INSERT dbo.WORKFLOW_INSTANCE_STEP_APPROVER(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID)
    SELECT DISTINCT s.WORKFLOW_INSTANCE_STEP_ID,u.EMPLOYEE_ID FROM dbo.WORKFLOW_INSTANCE_STEP s
    JOIN dbo.WORKFLOW_INSTANCE wi ON wi.WORKFLOW_INSTANCE_ID=s.WORKFLOW_INSTANCE_ID
    JOIN dbo.REQUISITION_HEADER h ON h.REQUISITION_ID=wi.REQUISITION_ID
    JOIN dbo.ROLE_MASTER rm ON rm.ROLE_CODE='MANAGER' AND rm.IS_ACTIVE=1
    JOIN dbo.DEV_USER_ROLE ur ON ur.ROLE_ID=rm.ROLE_ID AND ur.ORG_UNIT_ID=h.REQUESTED_ORG_UNIT_ID AND ur.IS_ACTIVE=1
    JOIN dbo.DEV_USER du ON du.DEV_USER_ID=ur.DEV_USER_ID AND du.IS_ACTIVE=1
    JOIN dbo.APP_USER_CACHE u ON u.EMPLOYEE_ID=du.EMPLOYEE_ID AND u.IS_ACTIVE=1
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.APPROVER_SOURCE='REQUESTING_UNIT_MANAGER';

    IF EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE_STEP s WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId AND s.IS_OPTIONAL=0 AND NOT EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER a WHERE a.WORKFLOW_INSTANCE_STEP_ID=s.WORKFLOW_INSTANCE_STEP_ID))
        THROW 50011, 'One or more required generic approval steps have no active approver.', 1;

    SELECT TOP(1) @FirstStepId=WORKFLOW_INSTANCE_STEP_ID,@FirstCode=STEP_CODE,@FirstOrg=u.ORG_UNIT_ID
    FROM dbo.WORKFLOW_INSTANCE_STEP s LEFT JOIN dbo.APPROVAL_UNIT u ON u.APPROVAL_UNIT_ID=s.APPROVAL_UNIT_ID
    WHERE s.WORKFLOW_INSTANCE_ID=@WorkflowInstanceId ORDER BY STEP_ORDER;
    UPDATE dbo.WORKFLOW_INSTANCE_STEP SET STEP_STATUS='ACTIVE',ACTIVATED_ON=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_STEP_ID=@FirstStepId;
    SELECT @FirstEmployee=MIN(EMPLOYEE_ID) FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER WHERE WORKFLOW_INSTANCE_STEP_ID=@FirstStepId;
    UPDATE dbo.WORKFLOW_INSTANCE SET CURRENT_STAGE=@FirstCode,CURRENT_OWNER_TYPE=CASE WHEN @FirstOrg IS NOT NULL THEN 'ORG_UNIT' ELSE 'EMPLOYEE' END,
      CURRENT_OWNER_EMPLOYEE_ID=CASE WHEN @FirstOrg IS NULL THEN @FirstEmployee END,CURRENT_OWNER_ORG_UNIT_ID=@FirstOrg,CURRENT_STATUS='PENDING',MODIFIED_DATE=SYSUTCDATETIME()
    WHERE WORKFLOW_INSTANCE_ID=@WorkflowInstanceId;
    COMMIT;
    SELECT '000' RESULT_CODE,N'Generic approval chain initialized.' RESULT_MESSAGE,@WorkflowInstanceId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_WorkflowApprovalChain_GetPending @EmployeeId VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT h.REQUISITION_ID,h.REQUISITION_NO,s.WORKFLOW_INSTANCE_STEP_ID,s.STEP_ORDER,s.STEP_CODE,s.STEP_NAME,s.APPROVAL_MODE,s.REQUIRED_APPROVAL_COUNT,s.ACTIVATED_ON
    FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER a
