CREATE OR ALTER PROCEDURE dbo.usp_ApprovalUnit_Upsert
    @ApprovalUnitId BIGINT = NULL,
    @ParentApprovalUnitId BIGINT = NULL,
    @OrgUnitId BIGINT = NULL,
    @UnitCode NVARCHAR(50),
    @UnitName NVARCHAR(150),
    @UnitType VARCHAR(20),
    @IsActive BIT = 1,
    @ActorEmployeeId VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    IF @UnitType NOT IN ('DIVISION','DEPARTMENT','UNIT','SECTION','TEAM') THROW 50001, 'Invalid approval unit type.', 1;
    IF @ApprovalUnitId IS NULL
    BEGIN
        INSERT dbo.APPROVAL_UNIT(PARENT_APPROVAL_UNIT_ID,ORG_UNIT_ID,UNIT_CODE,UNIT_NAME,UNIT_TYPE,IS_ACTIVE,CREATED_BY)
        VALUES(@ParentApprovalUnitId,@OrgUnitId,@UnitCode,@UnitName,@UnitType,@IsActive,@ActorEmployeeId);
        SET @ApprovalUnitId = SCOPE_IDENTITY();
    END
    ELSE
        UPDATE dbo.APPROVAL_UNIT SET PARENT_APPROVAL_UNIT_ID=@ParentApprovalUnitId, ORG_UNIT_ID=@OrgUnitId,
            UNIT_CODE=@UnitCode, UNIT_NAME=@UnitName, UNIT_TYPE=@UnitType, IS_ACTIVE=@IsActive,
            UPDATED_BY=@ActorEmployeeId, UPDATED_ON=SYSUTCDATETIME()
        WHERE APPROVAL_UNIT_ID=@ApprovalUnitId;
    SELECT '000' RESULT_CODE, N'Success' RESULT_MESSAGE, @ApprovalUnitId ENTITY_ID, CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_ApprovalUnit_GetAll @ActiveOnly BIT = 1
AS
BEGIN
    SET NOCOUNT ON;
    SELECT u.APPROVAL_UNIT_ID,u.PARENT_APPROVAL_UNIT_ID,u.ORG_UNIT_ID,u.UNIT_CODE,u.UNIT_NAME,u.UNIT_TYPE,u.IS_ACTIVE,
           p.UNIT_NAME PARENT_UNIT_NAME,o.ORG_UNIT_CODE,o.ORG_UNIT_NAME,
           (SELECT COUNT(*) FROM dbo.APPROVAL_UNIT_APPROVER a WHERE a.APPROVAL_UNIT_ID=u.APPROVAL_UNIT_ID AND a.IS_ACTIVE=1) ACTIVE_APPROVER_COUNT
    FROM dbo.APPROVAL_UNIT u
    LEFT JOIN dbo.APPROVAL_UNIT p ON p.APPROVAL_UNIT_ID=u.PARENT_APPROVAL_UNIT_ID
    LEFT JOIN dbo.ORG_UNIT o ON o.ORG_UNIT_ID=u.ORG_UNIT_ID
    WHERE @ActiveOnly=0 OR u.IS_ACTIVE=1
    ORDER BY u.UNIT_NAME;
END;
