IF OBJECT_ID('dbo.APP_DATABASE_VERSION', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_DATABASE_VERSION
    (
        APP_DATABASE_VERSION_ID BIGINT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_APP_DATABASE_VERSION PRIMARY KEY,
        VERSION_NO              VARCHAR(50) NOT NULL,
        RELEASE_NAME            NVARCHAR(150) NULL,
        APPLIED_ON              DATETIME2(0) NOT NULL
            CONSTRAINT DF_APP_DATABASE_VERSION_APPLIED_ON DEFAULT SYSUTCDATETIME(),
        CONSTRAINT UQ_APP_DATABASE_VERSION_VERSION_NO UNIQUE (VERSION_NO)
    );
END;
GO

IF NOT EXISTS (SELECT 1 FROM dbo.APP_DATABASE_VERSION WHERE VERSION_NO = 'DEV-2026.11.08.1')
BEGIN
    INSERT dbo.APP_DATABASE_VERSION(VERSION_NO, RELEASE_NAME)
    VALUES ('DEV-2026.11.08.1', N'Generic multi-level approval workflow');
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_SystemVersion_Get
AS
BEGIN
    SET NOCOUNT ON;

    SELECT TOP (1)
           VERSION_NO,
           RELEASE_NAME,
           APPLIED_ON,
           DB_NAME() AS DATABASE_NAME
    FROM dbo.APP_DATABASE_VERSION
    ORDER BY APP_DATABASE_VERSION_ID DESC;
END;
GO
