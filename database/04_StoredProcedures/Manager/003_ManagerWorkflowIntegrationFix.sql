CREATE OR ALTER PROCEDURE dbo.usp_Manager_Transition
 @RequisitionId BIGINT,@ActorEmployeeId VARCHAR(30),@Action VARCHAR(20),@Remarks NVARCHAR(2000)=NULL
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 BEGIN TRY
  BEGIN TRAN;
  DECLARE @org BIGINT,@status VARCHAR(40),@requester VARCHAR(30),@toStage VARCHAR(40),@newStatus VARCHAR(40),@actionType VARCHAR(50);
  SELECT @org=REQUESTED_ORG_UNIT_ID,@status=CURRENT_STATUS,@requester=REQUESTED_BY_EMPLOYEE_ID FROM dbo.REQUISITION_HEADER WITH(UPDLOCK,HOLDLOCK) WHERE REQUISITION_ID=@RequisitionId AND IS_ACTIVE=1;
  IF @status IS NULL THROW 51001,'Requisition not found.',1;
  IF @status<>'SUBMITTED' THROW 51003,'Manager action requires SUBMITTED status and cannot be repeated.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.APP_USER_CACHE u JOIN dbo.DEV_USER du ON du.EMPLOYEE_ID=u.EMPLOYEE_ID AND du.IS_ACTIVE=1 JOIN dbo.DEV_USER_ROLE ur ON ur.DEV_USER_ID=du.DEV_USER_ID AND ur.IS_ACTIVE=1 JOIN dbo.ROLE_MASTER r ON r.ROLE_ID=ur.ROLE_ID AND r.ROLE_CODE='MANAGER' WHERE u.EMPLOYEE_ID=@ActorEmployeeId AND u.ORG_UNIT_ID=@org) THROW 51002,'Actor is not an eligible manager for this organization.',1;
  IF @Action NOT IN('APPROVE','RETURN','REJECT') THROW 51000,'Invalid manager action.',1;
  IF @Action IN('RETURN','REJECT') AND NULLIF(LTRIM(RTRIM(@Remarks)),'') IS NULL THROW 51000,'Remarks are required for return and reject.',1;
  SELECT @toStage=CASE @Action WHEN'APPROVE'THEN'PROCUREMENT_OFFICER'WHEN'RETURN'THEN'DRAFT'ELSE'END'END,@newStatus=CASE @Action WHEN'APPROVE'THEN'IN_WORKFLOW'WHEN'RETURN'THEN'MANAGER_RETURNED'ELSE'MANAGER_REJECTED'END,@actionType=CONCAT('MANAGER_',@Action);
  UPDATE dbo.REQUISITION_ASSIGNMENT SET IS_CURRENT=0,RELEASED_DATE=SYSUTCDATETIME() WHERE REQUISITION_ID=@RequisitionId AND IS_CURRENT=1;
  UPDATE dbo.REQUISITION_HEADER SET CURRENT_STATUS=@newStatus,MODIFIED_BY=@ActorEmployeeId,MODIFIED_DATE=SYSUTCDATETIME() WHERE REQUISITION_ID=@RequisitionId;
  IF @Action='APPROVE' INSERT dbo.REQUISITION_ASSIGNMENT(REQUISITION_ID,ASSIGNMENT_TYPE,CREATED_BY) VALUES(@RequisitionId,'PROCUREMENT_OFFICER_POOL',@ActorEmployeeId);
  ELSE IF @Action='RETURN' INSERT dbo.REQUISITION_ASSIGNMENT(REQUISITION_ID,ASSIGNMENT_TYPE,ASSIGNED_TO_EMPLOYEE_ID,CREATED_BY) VALUES(@RequisitionId,'MAKER',@requester,@ActorEmployeeId);
  -- Workflow rule selection occurs later during Procurement Officer approval.
  -- Do not create WORKFLOW_INSTANCE here without a valid WORKFLOW_RULE_ID.
  IF EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE WHERE REQUISITION_ID=@RequisitionId AND COMPLETED_DATE IS NULL)
   UPDATE dbo.WORKFLOW_INSTANCE SET CURRENT_STAGE=@toStage,CURRENT_OWNER_TYPE=CASE @Action WHEN'APPROVE'THEN'ROLE_POOL'WHEN'RETURN'THEN'EMPLOYEE'ELSE'NONE'END,CURRENT_OWNER_EMPLOYEE_ID=CASE WHEN @Action='RETURN'THEN @requester END,CURRENT_OWNER_ORG_UNIT_ID=NULL,CURRENT_STATUS=CASE @Action WHEN'APPROVE'THEN'PENDING'WHEN'RETURN'THEN'RETURNED'ELSE'COMPLETED'END,COMPLETED_DATE=CASE WHEN @Action='REJECT'THEN SYSUTCDATETIME()END,MODIFIED_DATE=SYSUTCDATETIME() WHERE REQUISITION_ID=@RequisitionId AND COMPLETED_DATE IS NULL;
  INSERT dbo.APPROVAL_ACTION(REQUISITION_ID,ACTION_TYPE,ACTION_BY_EMPLOYEE_ID,ACTION_ROLE,FROM_STAGE,TO_STAGE,REMARKS) VALUES(@RequisitionId,@actionType,@ActorEmployeeId,'MANAGER','MANAGER',@toStage,@Remarks);
  INSERT dbo.WORKFLOW_HISTORY(REQUISITION_ID,FROM_STAGE,TO_STAGE,ACTION_TYPE,ACTION_BY_EMPLOYEE_ID,REMARKS) VALUES(@RequisitionId,'MANAGER',@toStage,@actionType,@ActorEmployeeId,@Remarks);
  COMMIT;
  SELECT'000'RESULT_CODE,N'Success'RESULT_MESSAGE,@RequisitionId ENTITY_ID,@toStage REFERENCE_NO;
 END TRY
 BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK;
  SELECT CASE ERROR_NUMBER()WHEN 51000 THEN'001'WHEN 51001 THEN'002'WHEN 51002 THEN'003'WHEN 51003 THEN'004'ELSE'999'END RESULT_CODE,ERROR_MESSAGE()RESULT_MESSAGE,@RequisitionId ENTITY_ID,NULL REFERENCE_NO;
 END CATCH
END;
GO
