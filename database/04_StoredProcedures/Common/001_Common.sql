CREATE OR ALTER PROCEDURE dbo.usp_Common_GetLookup @LookupCategory VARCHAR(50)
AS BEGIN SET NOCOUNT ON; SELECT LOOKUP_ID,LOOKUP_CODE,LOOKUP_NAME,DESCRIPTION,DISPLAY_ORDER FROM dbo.COMMON_LOOKUP WHERE LOOKUP_CATEGORY=@LookupCategory AND IS_ACTIVE=1 ORDER BY DISPLAY_ORDER,LOOKUP_NAME; END;
GO
CREATE OR ALTER PROCEDURE dbo.usp_Organization_GetAll @OrgUnitType VARCHAR(20)=NULL, @ActiveOnly BIT=1
AS BEGIN SET NOCOUNT ON; SELECT * FROM dbo.ORG_UNIT WHERE (@OrgUnitType IS NULL OR ORG_UNIT_TYPE=@OrgUnitType) AND (@ActiveOnly=0 OR IS_ACTIVE=1) ORDER BY ORG_UNIT_NAME; END;
GO
CREATE OR ALTER PROCEDURE dbo.usp_DevAuth_GetUser @Username VARCHAR(100)
AS BEGIN SET NOCOUNT ON; SELECT u.DEV_USER_ID,u.EMPLOYEE_ID,u.USERNAME,u.PASSWORD_HASH,c.DISPLAY_NAME,c.EMAIL,c.ORG_UNIT_ID,r.ROLE_CODE FROM dbo.DEV_USER u JOIN dbo.APP_USER_CACHE c ON c.EMPLOYEE_ID=u.EMPLOYEE_ID JOIN dbo.DEV_USER_ROLE ur ON ur.DEV_USER_ID=u.DEV_USER_ID AND ur.IS_ACTIVE=1 JOIN dbo.ROLE_MASTER r ON r.ROLE_ID=ur.ROLE_ID AND r.IS_ACTIVE=1 WHERE u.USERNAME=@Username AND u.IS_ACTIVE=1; END;
GO
CREATE OR ALTER PROCEDURE dbo.usp_Audit_GetByEntity @EntityName VARCHAR(100),@EntityId BIGINT
AS BEGIN SET NOCOUNT ON; SELECT * FROM dbo.AUDIT_LOG WHERE ENTITY_NAME=@EntityName AND ENTITY_ID=@EntityId ORDER BY ACTION_DATETIME,AUDIT_ID; END;
GO

