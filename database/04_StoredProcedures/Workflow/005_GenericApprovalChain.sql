    WHERE a.EMPLOYEE_ID=@EmployeeId AND a.DECISION_STATUS='PENDING' AND s.STEP_STATUS='ACTIVE' AND wi.CURRENT_STATUS IN ('PENDING','TAKEN')
    ORDER BY s.ACTIVATED_ON,h.REQUISITION_ID;
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_WorkflowApprovalChain_TryInitializeForRequisition
    @RequisitionId BIGINT,
    @ActorEmployeeId VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @WorkflowInstanceId BIGINT,@WorkflowRuleId BIGINT;
    SELECT TOP(1) @WorkflowInstanceId=WORKFLOW_INSTANCE_ID,@WorkflowRuleId=WORKFLOW_RULE_ID
    FROM dbo.WORKFLOW_INSTANCE
    WHERE REQUISITION_ID=@RequisitionId AND CURRENT_STATUS IN ('PENDING','TAKEN')
    ORDER BY WORKFLOW_INSTANCE_ID DESC;
    IF @WorkflowInstanceId IS NULL
    BEGIN
        SELECT '002' RESULT_CODE,N'No active workflow instance was found.' RESULT_MESSAGE,@RequisitionId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
        RETURN;
    END;
    IF NOT EXISTS(SELECT 1 FROM dbo.WORKFLOW_RULE_STEP WHERE WORKFLOW_RULE_ID=@WorkflowRuleId AND IS_ACTIVE=1)
    BEGIN
        SELECT '002' RESULT_CODE,N'No generic approval chain is configured for the matched workflow rule.' RESULT_MESSAGE,@RequisitionId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
        RETURN;
    END;
    IF EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE_STEP WHERE WORKFLOW_INSTANCE_ID=@WorkflowInstanceId)
    BEGIN
        SELECT '005' RESULT_CODE,N'The generic approval chain is already initialized.' RESULT_MESSAGE,@WorkflowInstanceId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
        RETURN;
    END;
    EXEC dbo.usp_WorkflowApprovalChain_Initialize @WorkflowInstanceId=@WorkflowInstanceId,@ActorEmployeeId=@ActorEmployeeId;
END;
GO

CREATE OR ALTER PROCEDURE dbo.usp_ConcernDivision_ForwardWithGenericChain
    @RequisitionId BIGINT,
    @ActorEmployeeId VARCHAR(30),
    @Remarks NVARCHAR(2000)=NULL,
    @BatchReferenceId UNIQUEIDENTIFIER=NULL
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    DECLARE @Forward TABLE(RESULT_CODE VARCHAR(10),RESULT_MESSAGE NVARCHAR(2000),ENTITY_ID BIGINT,REFERENCE_NO VARCHAR(50));
    DECLARE @Initialize TABLE(RESULT_CODE VARCHAR(10),RESULT_MESSAGE NVARCHAR(2000),ENTITY_ID BIGINT,REFERENCE_NO VARCHAR(50));
    BEGIN TRAN;
    INSERT @Forward EXEC dbo.usp_ConcernDivision_ForwardToAuthority @RequisitionId,@ActorEmployeeId,@Remarks,@BatchReferenceId;
    IF EXISTS(SELECT 1 FROM @Forward WHERE RESULT_CODE='000')
       AND EXISTS
       (
           SELECT 1 FROM dbo.WORKFLOW_INSTANCE wi
           JOIN dbo.WORKFLOW_RULE_STEP s ON s.WORKFLOW_RULE_ID=wi.WORKFLOW_RULE_ID AND s.IS_ACTIVE=1
           WHERE wi.REQUISITION_ID=@RequisitionId AND wi.CURRENT_STATUS IN ('PENDING','TAKEN')
       )
        INSERT @Initialize EXEC dbo.usp_WorkflowApprovalChain_TryInitializeForRequisition @RequisitionId,@ActorEmployeeId;
    COMMIT;
    SELECT RESULT_CODE,RESULT_MESSAGE,ENTITY_ID,REFERENCE_NO FROM @Forward;
END;
GO

