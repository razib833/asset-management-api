CREATE OR ALTER PROCEDURE dbo.usp_WorkflowApprovalChain_Action
    @WorkflowInstanceStepId BIGINT,
    @EmployeeId VARCHAR(30),
    @ActionType VARCHAR(15),
    @Remarks NVARCHAR(1000)=NULL,
    @BatchReference UNIQUEIDENTIFIER=NULL
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    IF @ActionType NOT IN ('APPROVE','RETURN','REJECT','SKIP') THROW 50012, 'Invalid generic workflow action.', 1;
    DECLARE @InstanceId BIGINT,@ReqId BIGINT,@RuleId BIGINT,@StepOrder INT,@StepCode VARCHAR(50),@Mode VARCHAR(15),@Required INT,@Optional BIT,@NextId BIGINT,@NextCode VARCHAR(50),@Destination VARCHAR(50),@Approved INT,@Eligible INT,@NextEmployee VARCHAR(30),@NextOrg BIGINT;
    SELECT @InstanceId=s.WORKFLOW_INSTANCE_ID,@StepOrder=s.STEP_ORDER,@StepCode=s.STEP_CODE,@Mode=s.APPROVAL_MODE,@Required=s.REQUIRED_APPROVAL_COUNT,@Optional=s.IS_OPTIONAL
    FROM dbo.WORKFLOW_INSTANCE_STEP s WHERE s.WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId AND s.STEP_STATUS='ACTIVE';
    IF @InstanceId IS NULL THROW 50013, 'The workflow step is not active.', 1;
    SELECT @ReqId=REQUISITION_ID,@RuleId=WORKFLOW_RULE_ID FROM dbo.WORKFLOW_INSTANCE WHERE WORKFLOW_INSTANCE_ID=@InstanceId;
    IF NOT EXISTS(SELECT 1 FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId AND EMPLOYEE_ID=@EmployeeId AND DECISION_STATUS='PENDING') THROW 50014, 'The user is not an eligible pending approver for this step.', 1;
    IF @ActionType='SKIP' AND @Optional=0 THROW 50015, 'A required workflow step cannot be skipped.', 1;

    BEGIN TRAN;
    INSERT dbo.WORKFLOW_STEP_ACTION(WORKFLOW_INSTANCE_STEP_ID,EMPLOYEE_ID,ACTION_TYPE,REMARKS,BATCH_REFERENCE) VALUES(@WorkflowInstanceStepId,@EmployeeId,@ActionType,@Remarks,@BatchReference);
    UPDATE dbo.WORKFLOW_INSTANCE_STEP_APPROVER SET DECISION_STATUS=CASE @ActionType WHEN 'APPROVE' THEN 'APPROVED' WHEN 'RETURN' THEN 'RETURNED' WHEN 'REJECT' THEN 'REJECTED' ELSE 'SKIPPED' END,DECISION_ON=SYSUTCDATETIME(),REMARKS=@Remarks
    WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId AND EMPLOYEE_ID=@EmployeeId;

    IF @ActionType IN ('RETURN','REJECT')
    BEGIN
        UPDATE dbo.WORKFLOW_INSTANCE_STEP SET STEP_STATUS=CASE @ActionType WHEN 'RETURN' THEN 'RETURNED' ELSE 'REJECTED' END,COMPLETED_ON=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId;
        UPDATE dbo.WORKFLOW_INSTANCE SET CURRENT_STATUS=CASE @ActionType WHEN 'RETURN' THEN 'RETURNED' ELSE 'REJECTED' END,CURRENT_OWNER_TYPE='NONE',CURRENT_OWNER_EMPLOYEE_ID=NULL,CURRENT_OWNER_ORG_UNIT_ID=NULL,MODIFIED_DATE=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_ID=@InstanceId;
        UPDATE dbo.REQUISITION_HEADER SET CURRENT_STATUS=CASE @ActionType WHEN 'RETURN' THEN 'RETURNED' ELSE 'REJECTED' END,MODIFIED_BY=@EmployeeId,MODIFIED_DATE=SYSUTCDATETIME() WHERE REQUISITION_ID=@ReqId;
        INSERT dbo.WORKFLOW_HISTORY(REQUISITION_ID,WORKFLOW_RULE_ID,FROM_STAGE,TO_STAGE,ACTION_TYPE,ACTION_BY_EMPLOYEE_ID,REMARKS,BATCH_REFERENCE_ID) VALUES(@ReqId,@RuleId,@StepCode,CASE @ActionType WHEN 'RETURN' THEN 'RETURNED' ELSE 'REJECTED' END,'GENERIC_STEP_'+@ActionType,@EmployeeId,@Remarks,@BatchReference);
        COMMIT; SELECT '000' RESULT_CODE,N'Action completed.' RESULT_MESSAGE,@ReqId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO; RETURN;
    END;

    SELECT @Approved=COUNT(*) FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId AND DECISION_STATUS='APPROVED';
    SELECT @Eligible=COUNT(*) FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId;
    IF @ActionType='SKIP' OR @Mode='ANY_ONE' AND @Approved>=1 OR @Mode='COUNT' AND @Approved>=@Required OR @Mode='ALL' AND @Approved=@Eligible
    BEGIN
        UPDATE dbo.WORKFLOW_INSTANCE_STEP SET STEP_STATUS=CASE WHEN @ActionType='SKIP' THEN 'SKIPPED' ELSE 'COMPLETED' END,COMPLETED_ON=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId;
        SELECT TOP(1) @NextId=WORKFLOW_INSTANCE_STEP_ID,@NextCode=STEP_CODE,@Destination=COMPLETION_DESTINATION,@NextOrg=u.ORG_UNIT_ID
        FROM dbo.WORKFLOW_INSTANCE_STEP s LEFT JOIN dbo.APPROVAL_UNIT u ON u.APPROVAL_UNIT_ID=s.APPROVAL_UNIT_ID
        WHERE s.WORKFLOW_INSTANCE_ID=@InstanceId AND s.STEP_ORDER>@StepOrder ORDER BY s.STEP_ORDER;
        IF @NextId IS NOT NULL
        BEGIN
            UPDATE dbo.WORKFLOW_INSTANCE_STEP SET STEP_STATUS='ACTIVE',ACTIVATED_ON=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_STEP_ID=@NextId;
            SELECT @NextEmployee=MIN(EMPLOYEE_ID) FROM dbo.WORKFLOW_INSTANCE_STEP_APPROVER WHERE WORKFLOW_INSTANCE_STEP_ID=@NextId;
            UPDATE dbo.WORKFLOW_INSTANCE SET CURRENT_STAGE=@NextCode,CURRENT_OWNER_TYPE=CASE WHEN @NextOrg IS NOT NULL THEN 'ORG_UNIT' ELSE 'EMPLOYEE' END,CURRENT_OWNER_EMPLOYEE_ID=CASE WHEN @NextOrg IS NULL THEN @NextEmployee END,CURRENT_OWNER_ORG_UNIT_ID=@NextOrg,MODIFIED_DATE=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_ID=@InstanceId;
            SET @Destination=@NextCode;
        END
        ELSE
        BEGIN
            SELECT @Destination=COALESCE(COMPLETION_DESTINATION,'READY_FOR_PROCUREMENT') FROM dbo.WORKFLOW_INSTANCE_STEP WHERE WORKFLOW_INSTANCE_STEP_ID=@WorkflowInstanceStepId;
            UPDATE dbo.WORKFLOW_INSTANCE SET CURRENT_STAGE=@Destination,CURRENT_OWNER_TYPE='NONE',CURRENT_OWNER_EMPLOYEE_ID=NULL,CURRENT_OWNER_ORG_UNIT_ID=NULL,CURRENT_STATUS=CASE WHEN @Destination='READY_FOR_PROCUREMENT' THEN 'COMPLETED' ELSE 'PENDING' END,COMPLETED_DATE=CASE WHEN @Destination='READY_FOR_PROCUREMENT' THEN SYSUTCDATETIME() END,MODIFIED_DATE=SYSUTCDATETIME() WHERE WORKFLOW_INSTANCE_ID=@InstanceId;
            IF @Destination='READY_FOR_PROCUREMENT' UPDATE dbo.REQUISITION_HEADER SET CURRENT_STATUS='READY_FOR_PROCUREMENT',MODIFIED_BY=@EmployeeId,MODIFIED_DATE=SYSUTCDATETIME() WHERE REQUISITION_ID=@ReqId;
        END;
        INSERT dbo.WORKFLOW_HISTORY(REQUISITION_ID,WORKFLOW_RULE_ID,FROM_STAGE,TO_STAGE,ACTION_TYPE,ACTION_BY_EMPLOYEE_ID,REMARKS,BATCH_REFERENCE_ID) VALUES(@ReqId,@RuleId,@StepCode,@Destination,'GENERIC_STEP_'+@ActionType,@EmployeeId,@Remarks,@BatchReference);
    END;
    COMMIT;
    SELECT '000' RESULT_CODE,N'Action completed.' RESULT_MESSAGE,@ReqId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
END;
GO
