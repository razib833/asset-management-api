CREATE OR ALTER PROCEDURE dbo.usp_ProcurementTracking_Search
 @RequisitionNo VARCHAR(30)=NULL,
 @OrgUnitId BIGINT=NULL,
 @AssetId BIGINT=NULL,
 @StatusCode VARCHAR(40)=NULL
AS
BEGIN
 SET NOCOUNT ON;
 SELECT p.PROCUREMENT_ID,h.REQUISITION_ID,h.REQUISITION_NO,h.REQUESTED_ORG_UNIT_ID,
        o.ORG_UNIT_NAME,h.TOTAL_ESTIMATED_AMOUNT,
        (SELECT STRING_AGG(CONVERT(NVARCHAR(MAX),x.ASSET_NAME),N', ') WITHIN GROUP(ORDER BY x.ASSET_NAME)
         FROM(SELECT DISTINCT am.ASSET_NAME FROM dbo.REQUISITION_ITEM ri JOIN dbo.ASSET_MASTER am ON am.ASSET_ID=ri.ASSET_ID WHERE ri.REQUISITION_ID=h.REQUISITION_ID AND ri.IS_ACTIVE=1)x) AS ASSETS,
        (SELECT STRING_AGG(CONVERT(NVARCHAR(MAX),x.REQ_TYPE),N', ') WITHIN GROUP(ORDER BY x.REQ_TYPE)
         FROM(SELECT DISTINCT ri.REQ_TYPE FROM dbo.REQUISITION_ITEM ri WHERE ri.REQUISITION_ID=h.REQUISITION_ID AND ri.IS_ACTIVE=1)x) AS REQUISITION_TYPES,
        s.STATUS_CODE,s.STATUS_NAME,p.PROCUREMENT_REFERENCE_NO,p.MODIFIED_DATE
 FROM dbo.PROCUREMENT_TRACKING p
 JOIN dbo.REQUISITION_HEADER h ON h.REQUISITION_ID=p.REQUISITION_ID
 JOIN dbo.ORG_UNIT o ON o.ORG_UNIT_ID=h.REQUESTED_ORG_UNIT_ID
 JOIN dbo.PROCUREMENT_STATUS_MASTER s ON s.STATUS_ID=p.CURRENT_STATUS_ID
 WHERE(@RequisitionNo IS NULL OR h.REQUISITION_NO LIKE @RequisitionNo+'%')
   AND(@OrgUnitId IS NULL OR h.REQUESTED_ORG_UNIT_ID=@OrgUnitId)
   AND(@StatusCode IS NULL OR s.STATUS_CODE=@StatusCode)
   AND(@AssetId IS NULL OR EXISTS(SELECT 1 FROM dbo.REQUISITION_ITEM i WHERE i.REQUISITION_ID=h.REQUISITION_ID AND i.ASSET_ID=@AssetId AND i.IS_ACTIVE=1))
 ORDER BY p.MODIFIED_DATE DESC;
END;
GO
