CREATE OR ALTER PROCEDURE dbo.usp_WorkflowRuleStep_Upsert
    @WorkflowRuleStepId BIGINT = NULL,
    @WorkflowRuleId BIGINT,
    @StepOrder INT,
    @StepCode VARCHAR(50),
    @StepName NVARCHAR(150),
    @ApproverSource VARCHAR(40),
    @ApprovalUnitId BIGINT = NULL,
    @EmployeeId VARCHAR(30) = NULL,
    @ApproverRoleCode VARCHAR(50) = NULL,
    @ApprovalMode VARCHAR(15) = 'ANY_ONE',
    @RequiredApprovalCount INT = 1,
    @IsOptional BIT = 0,
    @CompletionDestination VARCHAR(50) = NULL,
    @IsActive BIT = 1,
    @ActorEmployeeId VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON; SET XACT_ABORT ON;
    IF @StepOrder < 1 THROW 50004, 'Step order must be greater than zero.', 1;
    IF @ApprovalMode NOT IN ('ANY_ONE','ALL','COUNT') THROW 50005, 'Invalid approval mode.', 1;
    IF @ApproverSource NOT IN ('EMPLOYEE','APPROVAL_UNIT','ROLE_POOL','REQUESTING_UNIT_MANAGER','CONCERN_DIVISION_OFFICIAL','PROCUREMENT_AUTHORITY') THROW 50006, 'Invalid approver source.', 1;
    IF (@ApproverSource='EMPLOYEE' AND @EmployeeId IS NULL) OR (@ApproverSource='APPROVAL_UNIT' AND @ApprovalUnitId IS NULL) OR (@ApproverSource='ROLE_POOL' AND @ApproverRoleCode IS NULL)
        THROW 50007, 'The selected approver source requires a mapping value.', 1;
    IF @WorkflowRuleStepId IS NULL
    BEGIN
        INSERT dbo.WORKFLOW_RULE_STEP(WORKFLOW_RULE_ID,STEP_ORDER,STEP_CODE,STEP_NAME,APPROVER_SOURCE,APPROVAL_UNIT_ID,EMPLOYEE_ID,APPROVER_ROLE_CODE,APPROVAL_MODE,REQUIRED_APPROVAL_COUNT,IS_OPTIONAL,COMPLETION_DESTINATION,IS_ACTIVE,CREATED_BY)
        VALUES(@WorkflowRuleId,@StepOrder,@StepCode,@StepName,@ApproverSource,@ApprovalUnitId,@EmployeeId,@ApproverRoleCode,@ApprovalMode,@RequiredApprovalCount,@IsOptional,@CompletionDestination,@IsActive,@ActorEmployeeId);
        SET @WorkflowRuleStepId=SCOPE_IDENTITY();
    END
    ELSE
        UPDATE dbo.WORKFLOW_RULE_STEP SET WORKFLOW_RULE_ID=@WorkflowRuleId,STEP_ORDER=@StepOrder,STEP_CODE=@StepCode,
            STEP_NAME=@StepName,APPROVER_SOURCE=@ApproverSource,APPROVAL_UNIT_ID=@ApprovalUnitId,EMPLOYEE_ID=@EmployeeId,
            APPROVER_ROLE_CODE=@ApproverRoleCode,APPROVAL_MODE=@ApprovalMode,REQUIRED_APPROVAL_COUNT=@RequiredApprovalCount,
            IS_OPTIONAL=@IsOptional,COMPLETION_DESTINATION=@CompletionDestination,IS_ACTIVE=@IsActive,
            UPDATED_BY=@ActorEmployeeId,UPDATED_ON=SYSUTCDATETIME()
        WHERE WORKFLOW_RULE_STEP_ID=@WorkflowRuleStepId;
    SELECT '000' RESULT_CODE,N'Success' RESULT_MESSAGE,@WorkflowRuleStepId ENTITY_ID,CAST(NULL AS VARCHAR(50)) REFERENCE_NO;
END;
