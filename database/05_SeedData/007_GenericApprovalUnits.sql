USE [JamunaBankProcurement];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;

/* Idempotent development configuration for the example ICT chain:
   Concern Official -> ICT CCTV Unit Head -> ICT Head. */
DECLARE @Actor VARCHAR(30)='DEV-ADMIN-01';
DECLARE @IctOrgUnitId BIGINT=(SELECT ORG_UNIT_ID FROM dbo.ORG_UNIT WHERE ORG_UNIT_CODE='ICT');

IF @IctOrgUnitId IS NOT NULL
   AND EXISTS(SELECT 1 FROM dbo.APP_USER_CACHE WHERE EMPLOYEE_ID=@Actor)
BEGIN
    BEGIN TRAN;

    IF NOT EXISTS(SELECT 1 FROM dbo.APPROVAL_UNIT WHERE UNIT_CODE='ICT_DIVISION_APPROVAL')
        INSERT dbo.APPROVAL_UNIT(ORG_UNIT_ID,UNIT_CODE,UNIT_NAME,UNIT_TYPE,IS_ACTIVE,CREATED_BY)
        VALUES(@IctOrgUnitId,'ICT_DIVISION_APPROVAL','ICT Division','DIVISION',1,@Actor);

    DECLARE @IctDivisionApprovalId BIGINT=(SELECT APPROVAL_UNIT_ID FROM dbo.APPROVAL_UNIT WHERE UNIT_CODE='ICT_DIVISION_APPROVAL');

    IF NOT EXISTS(SELECT 1 FROM dbo.APPROVAL_UNIT WHERE UNIT_CODE='ICT_CCTV_UNIT')
        INSERT dbo.APPROVAL_UNIT(PARENT_APPROVAL_UNIT_ID,ORG_UNIT_ID,UNIT_CODE,UNIT_NAME,UNIT_TYPE,IS_ACTIVE,CREATED_BY)
        VALUES(@IctDivisionApprovalId,@IctOrgUnitId,'ICT_CCTV_UNIT','ICT CCTV Unit','UNIT',1,@Actor);

    DECLARE @CctvUnitId BIGINT=(SELECT APPROVAL_UNIT_ID FROM dbo.APPROVAL_UNIT WHERE UNIT_CODE='ICT_CCTV_UNIT');

    IF EXISTS(SELECT 1 FROM dbo.APP_USER_CACHE WHERE EMPLOYEE_ID='DEV-CA-02')
       AND NOT EXISTS(SELECT 1 FROM dbo.APPROVAL_UNIT_APPROVER WHERE APPROVAL_UNIT_ID=@CctvUnitId AND EMPLOYEE_ID='DEV-CA-02' AND APPROVER_ROLE_CODE='UNIT_HEAD')
        INSERT dbo.APPROVAL_UNIT_APPROVER(APPROVAL_UNIT_ID,EMPLOYEE_ID,APPROVER_ROLE_CODE,AUTHORITY_LEVEL,EFFECTIVE_FROM,IS_ACTIVE,CREATED_BY)
        VALUES(@CctvUnitId,'DEV-CA-02','UNIT_HEAD',1,'2026-01-01',1,@Actor);

    IF EXISTS(SELECT 1 FROM dbo.APP_USER_CACHE WHERE EMPLOYEE_ID='DEV-CA-01')
       AND NOT EXISTS(SELECT 1 FROM dbo.APPROVAL_UNIT_APPROVER WHERE APPROVAL_UNIT_ID=@IctDivisionApprovalId AND EMPLOYEE_ID='DEV-CA-01' AND APPROVER_ROLE_CODE='DIVISION_HEAD')
        INSERT dbo.APPROVAL_UNIT_APPROVER(APPROVAL_UNIT_ID,EMPLOYEE_ID,APPROVER_ROLE_CODE,AUTHORITY_LEVEL,EFFECTIVE_FROM,IS_ACTIVE,CREATED_BY)
        VALUES(@IctDivisionApprovalId,'DEV-CA-01','DIVISION_HEAD',1,'2026-01-01',1,@Actor);

    COMMIT;
END;
GO
