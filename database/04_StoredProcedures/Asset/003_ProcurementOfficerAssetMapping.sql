CREATE OR ALTER PROCEDURE dbo.usp_AssetOfficerMap_GetByAsset @AssetId BIGINT,@ActiveOnly BIT=1
AS BEGIN SET NOCOUNT ON; SELECT m.MAP_ID,m.ASSET_ID,m.EMPLOYEE_ID,m.IS_PRIMARY,m.EFFECTIVE_FROM,m.EFFECTIVE_TO,m.IS_ACTIVE,u.DISPLAY_NAME,u.EMAIL,u.DESIGNATION FROM dbo.PROC_OFFICER_ASSET_MAP m LEFT JOIN dbo.APP_USER_CACHE u ON u.EMPLOYEE_ID=m.EMPLOYEE_ID WHERE m.ASSET_ID=@AssetId AND (@ActiveOnly=0 OR m.IS_ACTIVE=1) ORDER BY m.IS_PRIMARY DESC,u.DISPLAY_NAME,m.EMPLOYEE_ID,m.EFFECTIVE_FROM; END;
GO
CREATE OR ALTER PROCEDURE dbo.usp_AssetOfficerMap_Deactivate @AssetId BIGINT,@MapId BIGINT,@Actor VARCHAR(50)
AS BEGIN SET NOCOUNT ON; UPDATE dbo.PROC_OFFICER_ASSET_MAP SET IS_ACTIVE=0,EFFECTIVE_TO=COALESCE(EFFECTIVE_TO,CONVERT(DATE,SYSUTCDATETIME())),MODIFIED_BY=@Actor,MODIFIED_DATE=SYSUTCDATETIME() WHERE MAP_ID=@MapId AND ASSET_ID=@AssetId AND IS_ACTIVE=1; SELECT CASE WHEN @@ROWCOUNT=1 THEN '000' ELSE '002' END RESULT_CODE,CASE WHEN @@ROWCOUNT=1 THEN N'Success' ELSE N'Active mapping not found' END RESULT_MESSAGE,@MapId ENTITY_ID,NULL REFERENCE_NO; END;
GO
