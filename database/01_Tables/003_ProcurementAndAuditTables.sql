USE [JamunaBankProcurement];
GO
CREATE TABLE dbo.PROCUREMENT_STATUS_MASTER (
 STATUS_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROC_STATUS PRIMARY KEY,
 STATUS_CODE VARCHAR(40) NOT NULL CONSTRAINT UQ_PROC_STATUS_CODE UNIQUE, STATUS_NAME NVARCHAR(150) NOT NULL,
 DESCRIPTION NVARCHAR(500) NULL, DISPLAY_ORDER INT NOT NULL, IS_ACTIVE BIT NOT NULL CONSTRAINT DF_PROC_STATUS_ACTIVE DEFAULT(1),
 CONSTRAINT CK_PROC_STATUS_ORDER CHECK(DISPLAY_ORDER>=0)
);
CREATE TABLE dbo.PROCUREMENT_TRACKING (
 PROCUREMENT_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROC_TRACKING PRIMARY KEY,
 REQUISITION_ID BIGINT NOT NULL CONSTRAINT UQ_PROC_TRACK_REQ UNIQUE, CURRENT_STATUS_ID BIGINT NOT NULL,
 RESPONSIBLE_EMPLOYEE_ID VARCHAR(30) NULL, PROCUREMENT_REFERENCE_NO VARCHAR(100) NULL, EXPECTED_COMPLETION_DATE DATE NULL,
 REMARKS NVARCHAR(2000) NULL, CREATED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_PROC_TRACK_CREATED DEFAULT SYSUTCDATETIME(),
 MODIFIED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_PROC_TRACK_MODIFIED DEFAULT SYSUTCDATETIME(), ROW_VERSION ROWVERSION NOT NULL,
 CONSTRAINT FK_PROC_TRACK_REQ FOREIGN KEY(REQUISITION_ID) REFERENCES dbo.REQUISITION_HEADER(REQUISITION_ID),
 CONSTRAINT FK_PROC_TRACK_STATUS FOREIGN KEY(CURRENT_STATUS_ID) REFERENCES dbo.PROCUREMENT_STATUS_MASTER(STATUS_ID),
 CONSTRAINT FK_PROC_TRACK_EMP FOREIGN KEY(RESPONSIBLE_EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID)
);
CREATE TABLE dbo.PROCUREMENT_STATUS_HISTORY (
 STATUS_HISTORY_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROC_STATUS_HISTORY PRIMARY KEY,
 PROCUREMENT_ID BIGINT NOT NULL, STATUS_ID BIGINT NOT NULL, STATUS_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_PROC_HIST_DATE DEFAULT SYSUTCDATETIME(),
 REFERENCE_NO VARCHAR(100) NULL, CHANGED_BY_EMPLOYEE_ID VARCHAR(30) NOT NULL, REMARKS NVARCHAR(2000) NULL,
 BATCH_REFERENCE_ID UNIQUEIDENTIFIER NULL, CREATED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_PROC_HIST_CREATED DEFAULT SYSUTCDATETIME(),
 CONSTRAINT FK_PROC_HIST_TRACK FOREIGN KEY(PROCUREMENT_ID) REFERENCES dbo.PROCUREMENT_TRACKING(PROCUREMENT_ID),
 CONSTRAINT FK_PROC_HIST_STATUS FOREIGN KEY(STATUS_ID) REFERENCES dbo.PROCUREMENT_STATUS_MASTER(STATUS_ID),
 CONSTRAINT FK_PROC_HIST_EMP FOREIGN KEY(CHANGED_BY_EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID)
);
CREATE TABLE dbo.WORK_ORDER_HEADER (
 WORK_ORDER_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_WORK_ORDER PRIMARY KEY,
 WORK_ORDER_NO VARCHAR(60) NOT NULL CONSTRAINT UQ_WORK_ORDER_NO UNIQUE, WORK_ORDER_DATE DATE NOT NULL,
 SUPPLIER_VENDOR NVARCHAR(300) NOT NULL, CONTRACT_AGREEMENT_NO VARCHAR(100) NULL, WORK_ORDER_VALUE DECIMAL(18,2) NOT NULL,
 DELIVERY_DATE DATE NULL, REMARKS NVARCHAR(2000) NULL, CREATED_BY VARCHAR(50) NOT NULL,
 CREATED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_WO_CREATED DEFAULT SYSUTCDATETIME(), MODIFIED_BY VARCHAR(50) NULL, MODIFIED_DATE DATETIME2(3) NULL,
 ROW_VERSION ROWVERSION NOT NULL, CONSTRAINT CK_WO_VALUE CHECK(WORK_ORDER_VALUE>=0), CONSTRAINT CK_WO_DELIVERY CHECK(DELIVERY_DATE IS NULL OR DELIVERY_DATE>=WORK_ORDER_DATE)
);
CREATE TABLE dbo.WORK_ORDER_REQUISITION (
 WORK_ORDER_ID BIGINT NOT NULL, REQUISITION_ID BIGINT NOT NULL, ALLOCATED_AMOUNT DECIMAL(18,2) NULL, REMARKS NVARCHAR(1000) NULL,
 CONSTRAINT PK_WORK_ORDER_REQ PRIMARY KEY(WORK_ORDER_ID,REQUISITION_ID),
 CONSTRAINT FK_WOR_WO FOREIGN KEY(WORK_ORDER_ID) REFERENCES dbo.WORK_ORDER_HEADER(WORK_ORDER_ID),
 CONSTRAINT FK_WOR_REQ FOREIGN KEY(REQUISITION_ID) REFERENCES dbo.REQUISITION_HEADER(REQUISITION_ID),
 CONSTRAINT CK_WOR_AMOUNT CHECK(ALLOCATED_AMOUNT IS NULL OR ALLOCATED_AMOUNT>=0)
);
CREATE TABLE dbo.COMMENT_NOTE (
 COMMENT_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_COMMENT_NOTE PRIMARY KEY,
 REQUISITION_ID BIGINT NOT NULL, REQ_ITEM_ID BIGINT NULL, COMMENT_TYPE VARCHAR(30) NOT NULL, COMMENT_TEXT NVARCHAR(4000) NOT NULL,
 CREATED_BY_EMPLOYEE_ID VARCHAR(30) NOT NULL, CREATED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_COMMENT_CREATED DEFAULT SYSUTCDATETIME(),
 IS_ACTIVE BIT NOT NULL CONSTRAINT DF_COMMENT_ACTIVE DEFAULT(1),
 CONSTRAINT FK_COMMENT_REQ FOREIGN KEY(REQUISITION_ID) REFERENCES dbo.REQUISITION_HEADER(REQUISITION_ID),
 CONSTRAINT FK_COMMENT_ITEM FOREIGN KEY(REQ_ITEM_ID) REFERENCES dbo.REQUISITION_ITEM(REQ_ITEM_ID),
 CONSTRAINT FK_COMMENT_EMP FOREIGN KEY(CREATED_BY_EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID)
);
CREATE TABLE dbo.ATTACHMENT (
 ATTACHMENT_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ATTACHMENT PRIMARY KEY,
 ENTITY_TYPE VARCHAR(30) NOT NULL, ENTITY_ID BIGINT NOT NULL, FILE_NAME NVARCHAR(255) NOT NULL, ORIGINAL_FILE_NAME NVARCHAR(255) NOT NULL,
 FILE_PATH_OR_STORAGE_KEY NVARCHAR(1000) NOT NULL, FILE_EXTENSION VARCHAR(20) NULL, MIME_TYPE VARCHAR(150) NULL, FILE_SIZE BIGINT NOT NULL,
 DOCUMENT_TYPE VARCHAR(50) NULL, UPLOADED_BY_EMPLOYEE_ID VARCHAR(30) NOT NULL, UPLOADED_DATE DATETIME2(3) NOT NULL CONSTRAINT DF_ATTACHMENT_UPLOADED DEFAULT SYSUTCDATETIME(),
 IS_ACTIVE BIT NOT NULL CONSTRAINT DF_ATTACHMENT_ACTIVE DEFAULT(1),
 CONSTRAINT FK_ATTACHMENT_EMP FOREIGN KEY(UPLOADED_BY_EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID),
 CONSTRAINT CK_ATTACHMENT_ENTITY CHECK(ENTITY_TYPE IN ('REQUISITION','REQUISITION_ITEM','APPROVAL','PROCUREMENT_STATUS','WORK_ORDER','COMMENT','OTHER')),
 CONSTRAINT CK_ATTACHMENT_SIZE CHECK(FILE_SIZE>=0)
);
CREATE TABLE dbo.AUDIT_LOG (
 AUDIT_ID BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AUDIT_LOG PRIMARY KEY,
 ENTITY_NAME VARCHAR(100) NOT NULL, ENTITY_ID BIGINT NULL, ACTION_TYPE VARCHAR(50) NOT NULL,
 OLD_VALUE_JSON NVARCHAR(MAX) NULL, NEW_VALUE_JSON NVARCHAR(MAX) NULL, ACTION_BY_EMPLOYEE_ID VARCHAR(30) NULL,
 ACTION_DATETIME DATETIME2(3) NOT NULL CONSTRAINT DF_AUDIT_DATE DEFAULT SYSUTCDATETIME(), IP_ADDRESS VARCHAR(45) NULL, CORRELATION_ID UNIQUEIDENTIFIER NULL,
 CONSTRAINT FK_AUDIT_EMP FOREIGN KEY(ACTION_BY_EMPLOYEE_ID) REFERENCES dbo.APP_USER_CACHE(EMPLOYEE_ID),
 CONSTRAINT CK_AUDIT_OLD_JSON CHECK(OLD_VALUE_JSON IS NULL OR ISJSON(OLD_VALUE_JSON)=1),
 CONSTRAINT CK_AUDIT_NEW_JSON CHECK(NEW_VALUE_JSON IS NULL OR ISJSON(NEW_VALUE_JSON)=1)
);
GO

