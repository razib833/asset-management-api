USE [JamunaBankProcurement];
GO
CREATE TYPE dbo.RequisitionItemTableType AS TABLE(
 CLIENT_ITEM_KEY INT NOT NULL PRIMARY KEY, ASSET_ID BIGINT NOT NULL, REQ_TYPE VARCHAR(20) NOT NULL,
 QUANTITY DECIMAL(18,2) NOT NULL, ESTIMATED_UNIT_PRICE DECIMAL(18,2) NOT NULL,
 PURPOSE_JUSTIFICATION NVARCHAR(2000) NOT NULL, ADDITIONAL_SPEC_REQUIREMENT NVARCHAR(2000) NULL,
 ASSET_TAG_NO NVARCHAR(100) NULL, SERIAL_NO NVARCHAR(100) NULL, CURRENT_CONDITION NVARCHAR(2000) NULL, REPLACEMENT_ADDITIONAL_INFO NVARCHAR(2000) NULL
);
GO
CREATE TYPE dbo.WorkOrderRequisitionTableType AS TABLE(REQUISITION_ID BIGINT NOT NULL PRIMARY KEY, ALLOCATED_AMOUNT DECIMAL(18,2) NULL, REMARKS NVARCHAR(1000) NULL);
GO
CREATE TYPE dbo.RequisitionSpecValueTableType AS TABLE(CLIENT_ITEM_KEY INT NOT NULL,ASSET_SPEC_ID BIGINT NOT NULL,SPEC_TEXT_VALUE NVARCHAR(1000) NULL,SPEC_NUM_VALUE DECIMAL(18,4) NULL,SPEC_DATE_VALUE DATE NULL,SPEC_BOOL_VALUE BIT NULL,PRIMARY KEY(CLIENT_ITEM_KEY,ASSET_SPEC_ID));
GO
CREATE TYPE dbo.RequisitionSpecOptionTableType AS TABLE(CLIENT_ITEM_KEY INT NOT NULL,ASSET_SPEC_ID BIGINT NOT NULL,ASSET_SPEC_OPTION_ID BIGINT NOT NULL,PRIMARY KEY(CLIENT_ITEM_KEY,ASSET_SPEC_ID,ASSET_SPEC_OPTION_ID));
GO
CREATE ROLE procurement_app_executor;
CREATE ROLE procurement_auditor;
GRANT SELECT ON dbo.AUDIT_LOG TO procurement_auditor;
GRANT SELECT ON dbo.APPROVAL_ACTION TO procurement_auditor;
GRANT SELECT ON dbo.WORKFLOW_HISTORY TO procurement_auditor;
DENY UPDATE, DELETE ON dbo.APPROVAL_ACTION TO procurement_app_executor;
DENY UPDATE, DELETE ON dbo.WORKFLOW_HISTORY TO procurement_app_executor;
DENY UPDATE, DELETE ON dbo.AUDIT_LOG TO procurement_app_executor;
GO
